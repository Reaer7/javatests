package com.gmail.reater.last.test.pattern.behavioral.iterator;

public class User {

    private String name;
    private int age;

    public User(final String name, final int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}
